function getDayOfYear(date, timeZone) {
  try {
    const parts = new Intl.DateTimeFormat('en-CA', {
      timeZone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).formatToParts(date);
    const values = Object.fromEntries(parts.map(({ type, value }) => [type, Number(value)]));
    const startOfYear = Date.UTC(values.year, 0, 1);
    const thisDay = Date.UTC(values.year, values.month - 1, values.day);
    return Math.floor((thisDay - startOfYear) / 86_400_000);
  } catch {
    const startOfYear = new Date(date.getFullYear(), 0, 1);
    return Math.floor((date - startOfYear) / 86_400_000);
  }
}

// Picks one reference per calendar day in the given timezone, so every user
// sees the same verse or hadith all day long.
export function getDailyIslamicReference(date = new Date(), timeZone = 'Asia/Dhaka') {
  const index = getDayOfYear(date, timeZone) % ISLAMIC_REFERENCES.length;
  return { ...ISLAMIC_REFERENCES[index], dayIndex: index };
}
